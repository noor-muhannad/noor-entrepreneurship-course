def paras(a): return "".join("<p>%s</p>" % E(x) for x in a)
def bullets(a, cls=""): return '<ul class="%s">%s</ul>' % (cls, "".join("<li>%s</li>" % E(x) for x in a))

TYPE_AR = {"video": "فيديو", "slides": "شرائح", "course": "كورس", "reading": "قراءة"}

def page(body, title):
    return """<!doctype html><html lang="ar" dir="rtl"><head><meta charset="utf-8"><title>%s</title><style>%s</style></head><body>%s</body></html>""" % (E(title), CSS, body)

def lecture_html(l):
    n = "%02d" % l["id"]
    part = next(p for p in meta["parts"] if p["id"] == l["part"])
    b = '<div class="top"><img src="../docs/assets/logo-web.png" alt="NOOR"><div class="ct">%s<br><span class="ltr">Noor Muhannad Ahmed</span></div></div>' % E(meta["course"]["title"]["ar"])
    b += '<div class="kick">Lecture %s · Part %d</div>' % (n, part["id"])
    b += "<h1>%s</h1>" % E(l["title"]["ar"])
    b += '<div class="en-title">%s</div>' % E(l["title"]["en"])
    b += '<span class="chip">%s · %s</span><span class="chip">ساعتان</span>' % (E(part["title"]["ar"]), E(part["title"]["en"]))
    b += "<h2>المصادر الأصلية</h2>"
    for s in l["sources"]:
        b += '<div class="src"><b>%s</b> <span class="chip">%s</span><div class="n">%s</div><div class="u">%s</div></div>' % (E(s["name"]), TYPE_AR.get(s["type"], s["type"]), E(s["note"]["ar"]), E(s["url"]))
    b += "<h2>ماذا ستتعلم</h2>" + bullets(l["objectives"]["ar"])
    b += '<div class="step"><div class="sn">1</div><div><h2>ملخص المصدر بالعربي</h2>%s</div></div>' % paras(l["summary_ar"])
    b += '<div class="step iraqi"><div class="sn">2</div><div><h2>الشرح بالعراقي</h2>%s</div></div>' % paras(l["explain_ar"])
    b += '<div class="step"><div class="sn">3</div><div class="en"><h2 style="direction:ltr">English summary (for revision)</h2>%s</div></div>' % bullets(l["summary_en"])
    b += '<div class="step"><div class="sn">4</div><div><h2>مثال تطبيقي</h2><p>%s</p><p class="en" style="color:#5D5066">%s</p></div></div>' % (E(l["example"]["ar"]), E(l["example"]["en"]))
    b += "<h2>مصطلحات المحاضرة</h2><table><thead><tr><th>Term</th><th>المعنى</th></tr></thead><tbody>%s</tbody></table>" % "".join("<tr><td>%s</td><td>%s</td></tr>" % (E(t["en"]), E(t["ar"])) for t in l["terms"])
    a = l["activity"]
    b += '<h2>&nbsp;</h2><div class="act"><h2>النشاط العملي</h2><p>%s</p><p class="en" style="color:#5D5066">%s</p><div class="d">الناتج المطلوب للمشروع الختامي: %s</div></div>' % (E(a["ar"]), E(a["en"]), E(a["deliverable"]["ar"]))
    b += "<h2>أسئلة مراجعة</h2>"
    for q in l["quiz"]:
        b += '<div class="q"><div class="qq">%s <span class="en" style="display:block;font-weight:400;color:#5D5066">%s</span></div><div class="aa">%s</div></div>' % (E(q["q"]["ar"]), E(q["q"]["en"]), E(q["a"]["ar"]))
    b += '<div class="notes"><h2>ملاحظاتي</h2>' + '<div class="ln"></div>' * 6 + "</div>"
    b += '<div class="foot">%s</div>' % E(meta["attribution"]["ar"])
    return page(b, "%s - %s" % (n, l["title"]["ar"]))

def capstone_html():
    c = meta["capstone"]
    b = '<div class="top"><img src="../docs/assets/logo-web.png" alt="NOOR"><div class="ct">%s<br><span class="ltr">Noor Muhannad Ahmed</span></div></div>' % E(meta["course"]["title"]["ar"])
    b += '<div class="kick">Capstone</div><h1>%s</h1><div class="en-title">%s</div><p>%s</p>' % (E(c["title"]["ar"]), E(c["title"]["en"]), E(c["intro"]["ar"]))
    b += "<p><b>اسم الطالب:</b> ____________________ &nbsp; <b>اسم المشروع:</b> ____________________ &nbsp; <b>التاريخ:</b> ____________</p>"
    for l in lectures:
        b += '<div class="cap-sec"><h3>%02d · %s</h3><div style="font-size:9.5pt;color:#5D5066;margin-bottom:3pt">%s</div>%s</div>' % (l["id"], E(l["title"]["ar"]), E(l["activity"]["deliverable"]["ar"]), '<div class="ln"></div>' * 4)
    b += '<h2>عرض من 7 شرائح (10 دقائق)</h2><ol><li>مقدمة وشعار جذاب</li><li>الزبون المستهدف وألمه</li><li>الحل</li><li>خطة الدخول للسوق</li><li>الأرقام المالية</li><li>الفريق والمنافسة</li><li>الخلاصة والطلب المحدد</li></ol>'
    b += "<h2>معيار التقييم المقترح</h2><table><thead><tr><th>Criterion</th><th>%s</th></tr></thead><tbody>%s</tbody></table>" % ("الدرجة", "".join("<tr><td style='direction:rtl;text-align:start;font-weight:400;color:#251B2B'>%s</td><td>%d</td></tr>" % (E(r["name"]["ar"]), r["w"]) for r in c["rubric"]))
    b += '<div class="foot">%s</div>' % E(meta["attribution"]["ar"])
    return page(b, "Capstone template")

from playwright.sync_api import sync_playwright

jobs = [("lecture-%02d" % l["id"], lecture_html(l)) for l in lectures] + [("capstone-template", capstone_html())]
FOOT = '<div style="width:100%;font-size:8px;color:#62556B;text-align:center;font-family:sans-serif"><span class="pageNumber"></span> / <span class="totalPages"></span></div>'
with sync_playwright() as p:
    br = p.chromium.launch()
    for name, doc in jobs:
        path = os.path.join(SRC, name + ".html")
        open(path, "w", encoding="utf-8").write(doc)
        pg = br.new_page()
        pg.goto("file://" + path)
        pg.wait_for_timeout(300)
        pg.evaluate("document.fonts.ready")
        out = os.path.join(SITE, "pdf", name + ".pdf")
        pg.pdf(path=out, format="A4", margin={"top": "16mm", "bottom": "16mm", "left": "15mm", "right": "15mm"}, print_background=True,
               display_header_footer=True, header_template="<span></span>", footer_template=FOOT)
        pg.close()
        print("pdf:", name, os.path.getsize(out) // 1024, "KB")
    br.close()
