#!/usr/bin/env python3
"""Build script for the NOOR entrepreneurship course site.

1. Merges data/meta.json + data/lectures/L*.json into site/data/course.js
2. Renders one study-sheet PDF per lecture (+ a capstone template) with Chromium.

Usage:  python3 build.py [--no-pdf]
"""
import glob, html, json, os, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(ROOT, "docs")
SRC = os.path.join(ROOT, "pdfsrc")
os.makedirs(SRC, exist_ok=True)
os.makedirs(os.path.join(SITE, "pdf"), exist_ok=True)

# ---------- 1. merge data ----------
meta = json.load(open(os.path.join(SITE, "data", "meta.json"), encoding="utf-8"))
lectures = [json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob(os.path.join(SITE, "data", "lectures", "L*.json")))]
lectures.sort(key=lambda d: d["id"])
course = {
    "version": meta["version"],
    "course": meta["course"],
    "parts": meta["parts"],
    "capstone": meta["capstone"],
    "attribution": meta["attribution"],
    "lectures": lectures,
}
with open(os.path.join(SITE, "data", "course.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by build.py from meta.json and lectures/L*.json. Do not edit by hand. */\n")
    f.write("window.COURSE = " + json.dumps(course, ensure_ascii=False, indent=1) + ";\n")
print("course.js written:", len(lectures), "lectures")

if "--no-pdf" in sys.argv:
    sys.exit(0)

